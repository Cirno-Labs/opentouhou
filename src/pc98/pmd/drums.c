static void M_Write(
    const SSG_EFFECTS *const effects, const uint8_t reg, const uint8_t value)
{
    PmdChip_PercussionWrite(effects->chip, reg, value);
}

static RESULT M_Frame(SSG_EFFECTS *const effects, const uint16_t position)
{
    FAIL_IF(position >= effects->bank->size, "SSG effect exceeds table");
    const uint8_t *const p = effects->bank->bytes + position;
    if (p[0] == 255) {
        SsgEffects_Stop(effects);
        return OK;
    }
    FAIL_IF(effects->bank->size - position < 11, "Truncated SSG effect frame");
    effects->count = p[0];
    effects->tone = (uint16_t)(p[1] | (uint16_t)p[2] << 8);
    effects->noise = p[3];
    M_Write(effects, 4, p[1]);
    M_Write(effects, 5, p[2]);
    M_Write(effects, 6, p[3]);
    M_Write(
        effects, 7,
        (uint8_t)((effects->chip->registers[7] & 0xdb) | ((p[4] << 2) & 0x24)));
    for (uint8_t i = 0; i < 4; i++) {
        M_Write(effects, (uint8_t)(10 + i), p[5 + i]);
    }
    effects->tone_sweep = (int8_t)p[9];
    effects->noise_sweep = p[10];
    effects->noise_count = p[10] & 15;
    effects->position = (uint16_t)(position + 11);
    return OK;
}

