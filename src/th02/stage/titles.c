static STAGE_TITLES m_Titles;

static TRAM_TEXT *M_Field(STAGE_TITLE_ASSETS *const assets, const size_t index)
{
    return index < 6  ? &assets->stages[index]
        : index < 18  ? &assets->music[index - 6]
        : index == 18 ? &assets->blank
                      : &assets->music_blank;
}

static RESULT M_Text(
    const uint8_t *const bytes, const size_t size,
    const ALLOCATOR *const allocator, TRAM_TEXT *const out)
{
    READER reader;
    Reader_OpenBuffer(&reader, bytes, size, nullptr);
    const RESULT result = TramText_Read(&reader, size, allocator, out);
    Reader_Close(&reader);
    return result;
}

static RESULT M_Load(STAGE_TITLE_ASSETS *const assets)
{
    memcpy(assets->stage_label, m_StageLabel, sizeof(assets->stage_label));
    memcpy(assets->extra_label, m_ExtraLabel, sizeof(assets->extra_label));
    memcpy(assets->demo_label, m_DemoLabel, sizeof(assets->demo_label));
    memcpy(assets->halfwidths, m_Halfwidths, sizeof(assets->halfwidths));
    for (size_t i = 0; i < 6; i++) {
        MUST(M_Text(
            m_Stages[i], m_StageSizes[i], &assets->allocator,
            M_Field(assets, i)));
    }
    for (size_t i = 0; i < 12; i++) {
        MUST(M_Text(
            m_Music[i], sizeof(m_Music[i]), &assets->allocator,
            M_Field(assets, 6 + i)));
    }
    MUST(M_Text(
        m_Blank, sizeof(m_Blank), &assets->allocator, M_Field(assets, 18)));
    MUST(M_Text(
        m_MusicBlank, sizeof(m_MusicBlank), &assets->allocator,
        M_Field(assets, 19)));
    return OK;
}

RESULT StageTitles_Load(
    const ALLOCATOR *const allocator, STAGE_TITLE_ASSETS *const out)
{
    memset(out, 0, sizeof(*out));
    out->allocator = *allocator;
    const RESULT result = M_Load(out);
    if (!IS_OK(result)) {
        StageTitles_Free(out);
    }
    return result;
}

void StageTitles_Free(STAGE_TITLE_ASSETS *const assets)
{
    for (size_t i = 0; i < 20; i++) {
        const TRAM_TEXT *const text = M_Field(assets, i);
        if (text->text != nullptr) {
            Allocator_Free(
                &assets->allocator, (void *)text->text, strlen(text->text) + 1);
        }
        Allocator_Free(
            &assets->allocator, (void *)text->characters,
            (size_t)text->count * sizeof(*text->characters));
    }
    memset(assets, 0, sizeof(*assets));
}

void StageTitles_Begin(
    const STAGE_TITLE_ASSETS *const assets, const uint8_t stage,
    const bool demo)
{
    ASSERT(stage < 6);
    memset(&m_Titles, 0, sizeof(m_Titles));
    m_Titles.assets = assets;

    m_Titles.stage = stage;
    m_Titles.demo = demo;
    m_Titles.banner_active = true;
    m_Titles.music_id = stage * 2;
    m_Titles.music_timer = demo ? 0 : 1;
}

void StageTitles_Reveal(void)
{
    const STAGE_TITLE_ASSETS *const assets = m_Titles.assets;
    if (m_Titles.demo) {
        Tram_PutGaijiString(18, 12, assets->demo_label, 0xc3);
    } else {
        if (m_Titles.stage == 5) {
            Tram_PutGaijiString(16, 12, assets->extra_label, 0xc1);
        } else {
            uint8_t label[sizeof(assets->stage_label)];
            memcpy(label, assets->stage_label, sizeof(label));
            label[5] += m_Titles.stage;
            Tram_PutGaijiString(22, 12, label, 0xc1);
        }
        Tram_PutText(
            28 - assets->halfwidths[m_Titles.stage], 13,
            &assets->stages[m_Titles.stage], UINT16_MAX, 0xe1);
    }
}

void StageTitles_Update(const uint32_t frame)
{
    if (!m_Titles.banner_active || frame != 160) {
        return;
    }
    if (!m_Titles.demo) {
        Tram_PutText(4, 12, &m_Titles.assets->blank, UINT16_MAX, 0xe1);
        Tram_PutText(4, 13, &m_Titles.assets->blank, UINT16_MAX, 0xe1);
    }
    m_Titles.banner_active = false;
}

void StageTitles_UpdateMusic(void)
{
    if (m_Titles.music_timer == 0) {
        return;
    }
    if (m_Titles.music_timer == 1) {
        Tram_PutGaiji(24, 23, 0xd8, 0xc1);
        Tram_PutText(
            26, 23, &m_Titles.assets->music[m_Titles.music_id], UINT16_MAX,
            0xe1);
    }
    m_Titles.music_timer++;
    if (m_Titles.music_timer >= 160) {
        Tram_PutText(24, 23, &m_Titles.assets->music_blank, UINT16_MAX, 0xe1);
        m_Titles.music_timer = 0;
    }
}

void StageTitles_Boss(void)
{
    m_Titles.music_id = m_Titles.stage * 2 + 1;
    m_Titles.music_timer = 1;
}
