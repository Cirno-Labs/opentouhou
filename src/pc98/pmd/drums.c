RESULT SsgEffects_LoadTable(SSG_EFFECT_BANK *const out)
{
    memset(out, 0, sizeof(*out));
    const size_t size = sizeof(m_Table);
    const uint16_t first = (uint16_t)(m_Table[1] | (uint16_t)m_Table[2] << 8);
    FAIL_IF(
        first < 3 || first % 3 != 0 || first / 3 > SSG_EFFECT_LIMIT
            || first >= size,
        "Invalid SSG effect entry count");
    SSG_EFFECT_BANK bank = { .bytes = m_Table,
                             .size = size,
                             .count = (uint8_t)(first / 3) };
    for (uint8_t i = 0; i < bank.count; i++) {
        bank.priorities[i] = m_Table[i * 3];
        bank.offsets[i] =
            (uint16_t)(m_Table[i * 3 + 1] | (uint16_t)m_Table[i * 3 + 2] << 8);
        FAIL_IF(
            bank.offsets[i] < first || bank.offsets[i] >= size,
            "SSG effect offset exceeds table");
    }
    for (uint8_t i = 0; i < bank.count; i++) {
        size_t position = bank.offsets[i];
        for (;;) {
            FAIL_IF(position >= size, "Missing SSG effect terminator");
            if (m_Table[position] == 255) {
                break;
            }
            FAIL_IF(size - position < 11, "Truncated SSG effect frame");
            position += 11;
        }
    }
    *out = bank;
    return OK;
}

void SsgEffects_Init(
    SSG_EFFECTS *const effects, const SSG_EFFECT_BANK *const bank,
    PMD_CHIP *const chip)
{
    memset(effects, 0, sizeof(*effects));
    effects->id = 255;
    effects->bank = bank;
    effects->chip = chip;
}

RESULT SsgEffects_Play(SSG_EFFECTS *const effects, const uint8_t id)
{
    FAIL_IF(
        effects->bank == nullptr || id >= effects->bank->count,
        "Invalid SSG effect ID");
    effects->id = id;
    const uint8_t priority = effects->bank->priorities[id];
    if (effects->priority <= priority) {
        MUST(M_Frame(effects, effects->bank->offsets[id]));
        effects->priority = priority;
    }
    return OK;
}

RESULT SsgEffects_Step(SSG_EFFECTS *const effects)
{
    if (effects->priority == 0) {
        return OK;
    }
    if (--effects->count == 0) {
        return M_Frame(effects, effects->position);
    }
    effects->tone = (uint16_t)(effects->tone + effects->tone_sweep);
    M_Write(effects, 4, (uint8_t)effects->tone);
    M_Write(effects, 5, (uint8_t)(effects->tone >> 8));
    M_Write(effects, 7, effects->chip->registers[7]);
    if (effects->noise_sweep != 0 && --effects->noise_count == 0) {
        effects->noise_count = effects->noise_sweep & 15;
        effects->noise =
            (uint8_t)(effects->noise
                      + (int8_t)(effects->noise_sweep & 0xf0) / 16);
        M_Write(effects, 6, effects->noise);
    }
    return OK;
}

void SsgEffects_Stop(SSG_EFFECTS *const effects)
{
    M_Write(effects, 10, 0);
    M_Write(effects, 7, (uint8_t)((effects->chip->registers[7] & 0xdb) | 0x24));
    effects->priority = 0;
    effects->id = 255;
}
